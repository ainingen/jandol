  const FALLBACK = PLAYER_LINES;

  /* 場面に合う一言を返す。無ければ null（何も言わせない） */
  function pick(chara, kind, rng) {
    rng = rng || Math.random;
    const set = (chara && LINES[chara]) || FALLBACK;
    const list = set[kind] || FALLBACK[kind];
    if (!list || !list.length) return null;
    return list[Math.floor(rng() * list.length)];
  }

