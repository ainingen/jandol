  function prefsOf(region) { return PREFS.filter((p) => p.region === region); }

  /* 県庁所在地どうしの球面距離（km）。半径6371kmのハバサイン。
     引数は県 key でも県そのものでもよい。**対称**（テストで固定してある） */
  function distKm(a, b) {
    const p = typeof a === 'string' ? prefOf(a) : a;
    const q = typeof b === 'string' ? prefOf(b) : b;
    if (!p || !q) return 0;
    const R = 6371, rad = Math.PI / 180;
    const dLat = (q.lat - p.lat) * rad, dLng = (q.lng - p.lng) * rad;
    const s = Math.sin(dLat / 2) ** 2
      + Math.cos(p.lat * rad) * Math.cos(q.lat * rad) * Math.sin(dLng / 2) ** 2;
    return 2 * R * Math.asin(Math.min(1, Math.sqrt(s)));
  }

  /* 遠さの段階。**遠征の日数と費用は km ではなくこの段階から出す**（spec.md §7.2）。
     段階にしておくと、数字を触るときこの表一枚で済む。
     京都からだと 大阪0・名古屋1・東京2・福岡3・札幌4・那覇5 になる */
  const FAR_KM = [80, 250, 500, 800, 1200];

  function farOf(km) {
    for (let i = 0; i < FAR_KM.length; i++) if (km <= FAR_KM[i]) return i;
    return FAR_KM.length;
  }

  /* 二つの県のあいだの遠さ。distKm と farOf を続けて呼ぶだけ */
  function farBetween(a, b) { return farOf(distKm(a, b)); }

  return { PREFS, FAR_KM, prefOf, prefsOf, distKm, farOf, farBetween };
